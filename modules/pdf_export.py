def _single_order_card_story(label, fields, doc):
    """Return flowables for a single order card (reused by sales & purchase)."""
    from reportlab.lib.styles import getSampleStyleSheet as _gss, ParagraphStyle as _PS
    from reportlab.platypus import Paragraph as _P, Spacer as _Sp, Table as _T, TableStyle as _TS

    styles = _gss()
    story = []

    title_style = _PS("orderTitle", parent=styles["Heading1"], fontSize=20, leading=24,
                       textColor=colors.HexColor("#0f172a"), spaceAfter=2)
    story.append(_P(f"<b>{label}</b>", title_style))

    rows = []
    for k, v in fields:
        key_p = _P(f"<b>{k}</b>", _PS("fk", parent=styles["BodyText"], fontSize=10,
                                       textColor=colors.HexColor("#475569")))
        val_p = _P(str(v) if v is not None else "—", _PS("fv", parent=styles["BodyText"],
                                                          fontSize=10, textColor=colors.HexColor("#0f172a")))
        rows.append([key_p, val_p])

    info_table = _T(rows, colWidths=[45 * mm, 120 * mm])
    info_table.setStyle(_TS([
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f1f5f9")),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#cbd5e1")),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
    ]))
    story.append(_Sp(1, 4 * mm))
    story.append(info_table)
    return story


